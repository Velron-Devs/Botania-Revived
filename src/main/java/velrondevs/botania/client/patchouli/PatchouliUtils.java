package velrondevs.botania.client.patchouli;

import net.minecraft.client.Minecraft;
import net.minecraft.core.HolderLookup;
import net.minecraft.resources.Identifier;
import net.minecraft.world.item.ItemStack;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.util.context.ContextMap;
import net.minecraft.world.item.crafting.CraftingRecipe;
import net.minecraft.world.item.crafting.Ingredient;
import net.minecraft.world.item.crafting.ShapedRecipe;
import net.minecraft.world.item.crafting.display.RecipeDisplay;
import net.minecraft.world.item.crafting.display.SlotDisplayContext;
import net.minecraft.world.item.crafting.Recipe;
import net.minecraft.world.item.crafting.RecipeHolder;
import net.minecraft.world.item.crafting.RecipeInput;
import net.minecraft.world.item.crafting.RecipeType;
import net.minecraft.world.level.Level;

import org.jetbrains.annotations.Nullable;

import velrondevs.botania.api.BotaniaAPI;
import velrondevs.botania.registry.BotaniaRecipeTypes;
import velrondevs.botania.xplat.XplatAbstractions;
import vazkii.patchouli.api.IVariable;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.stream.Collectors;

public class PatchouliUtils {
	private static boolean crafttweakerInfoNote = false;
	private static boolean inVisualizer;

	public static <T extends Recipe<I>, I extends RecipeInput> T getRecipe(Level level, RecipeType<T> type, Identifier id) {
		RecipeHolder<T> holder = getRecipeHolder(level, type, id);
		return holder == null ? null : holder.value();
	}

	public static <T extends Recipe<I>, I extends RecipeInput> RecipeHolder<T> getRecipeHolder(Level level, RecipeType<T> type, Identifier id) {
		Map<Identifier, T> map = BotaniaRecipeTypes.getRecipes(level, type);
		for (Identifier candidate : List.of(id,
				Identifier.fromNamespaceAndPath("crafttweaker", id.getPath()),
				Identifier.fromNamespaceAndPath("crafttweaker", "autogenerated/" + id.getNamespace() + "." + id.getPath()))) {
			T r = map.get(candidate);
			if (r != null) {
				return new RecipeHolder<>(ResourceKey.create(Registries.RECIPE, candidate), r);
			}
		}

		BotaniaAPI.LOGGER.warn("Template references nonexistent recipe {} of type {}", id, type);
		if (!crafttweakerInfoNote) {
			crafttweakerInfoNote = true;
			if (XplatAbstractions.INSTANCE.isModLoaded("crafttweaker")) {
				BotaniaAPI.LOGGER.info("""
					To add a recipe that replaces a builtin recipe with CT,\s
					add one with the same type, named the same as the path of the missing recipe.
					eg. for recipe {}, add a recipe named "{}".""", id, id.getPath());
			}
		}
		return null;
	}

	public static <T extends Recipe<I>, I extends RecipeInput> List<T> getRecipeGroup(RecipeType<T> type, String group) {
		Map<Identifier, T> map = BotaniaRecipeTypes.getRecipes(Minecraft.getInstance().level, type);
		List<T> list = new ArrayList<>();
		for (T value : map.values()) {
			if (group.equals(value.group())) {
				list.add(value);
			}
		}
		if (list.isEmpty()) {
			BotaniaAPI.LOGGER.warn("Template references empty group {} of recipe type {}", group, type);
		}
		return list;
	}

	public static IVariable interweaveIngredients(List<Ingredient> ingredients, int longestIngredientSize, HolderLookup.Provider registries) {
		if (ingredients.size() == 1) {
			return IVariable.wrapList(Arrays.stream(getItems(ingredients.get(0))).map(v -> IVariable.from(v, registries)).collect(Collectors.toList()), registries);
		}

		ItemStack[] empty = { ItemStack.EMPTY };
		List<ItemStack[]> stacks = new ArrayList<>();
		for (Ingredient ingredient : ingredients) {
			if (ingredient != null && !ingredient.isEmpty()) {
				stacks.add(getItems(ingredient));
			} else {
				stacks.add(empty);
			}
		}
		List<IVariable> list = new ArrayList<>(stacks.size() * longestIngredientSize);
		for (int i = 0; i < longestIngredientSize; i++) {
			for (ItemStack[] stack : stacks) {
				list.add(IVariable.from(stack[i % stack.length], registries));
			}
		}
		return IVariable.wrapList(list, registries);
	}

	public static IVariable interweaveIngredients(List<Ingredient> ingredients, HolderLookup.Provider registries) {
		return interweaveIngredients(ingredients, ingredients.stream().mapToInt(ingr -> getItems(ingr).length).max().orElse(1), registries);
	}

	public static ItemStack[] getItems(@Nullable Ingredient ingredient) {
		if (ingredient == null) {
			return new ItemStack[] { ItemStack.EMPTY };
		}
		ItemStack[] ret = ingredient.items().map(ItemStack::new).toArray(ItemStack[]::new);
		return ret.length == 0 ? new ItemStack[] { ItemStack.EMPTY } : ret;
	}

	public static List<Ingredient> getCraftingIngredients(CraftingRecipe recipe) {
		if (recipe instanceof ShapedRecipe shaped) {
			List<Ingredient> ret = new ArrayList<>();
			for (Optional<Ingredient> ingredient : shaped.getIngredients()) {
				ret.add(ingredient.orElse(null));
			}
			return ret;
		}
		return recipe.placementInfo().ingredients();
	}

	public static ItemStack getDisplayResult(Recipe<?> recipe, Level level) {
		ContextMap context = SlotDisplayContext.fromLevel(level);
		for (RecipeDisplay display : recipe.display()) {
			ItemStack stack = display.result().resolveForFirstStack(context);
			if (!stack.isEmpty()) {
				return stack;
			}
		}
		return ItemStack.EMPTY;
	}

	public static boolean isInVisualizer() {
		return inVisualizer;
	}

	public static void setInVisualizer(boolean inVisualization) {
		PatchouliUtils.inVisualizer = inVisualization;
	}
}
